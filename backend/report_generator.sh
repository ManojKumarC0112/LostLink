#!/usr/bin/env bash
# ==============================================================================
# LostLink - Unix & Shell Scripting Campus Lost & Found System
# Module: report_generator.sh (Member 4: Automated Report Generation)
# Commands Used: date, awk, grep, sort, wc, cat, redirection
# ==============================================================================

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "$SCRIPT_DIR/utils.sh"

generate_report() {
    local report_type="${1:-daily}" # daily, weekly, monthly
    local format="${2:-all}"        # txt, html, or all
    local generated_by="${3:-system}"

    local timestamp_file timestamp_readable
    timestamp_file=$(date "+%Y%m%d_%H%M%S")
    timestamp_readable=$(date "+%A, %B %d, %Y %I:%M %p")

    local txt_path="$REPORTS_DIR/report_${report_type}_${timestamp_file}.txt"
    local html_path="$REPORTS_DIR/report_${report_type}_${timestamp_file}.html"

    # Gather data from analytics module
    local stats_json
    stats_json=$("$SCRIPT_DIR/analytics.sh" stats --json)

    local t_lost t_found p_claims t_returned rec_rate
    t_lost=$(echo "$stats_json" | grep '"total_lost":' | awk -F': ' '{print $2}' | tr -d ',')
    t_found=$(echo "$stats_json" | grep '"total_found":' | awk -F': ' '{print $2}' | tr -d ',')
    p_claims=$(echo "$stats_json" | grep '"pending_claims":' | awk -F': ' '{print $2}' | tr -d ',')
    t_returned=$(echo "$stats_json" | grep '"returned_items":' | awk -F': ' '{print $2}' | tr -d ',')
    rec_rate=$(echo "$stats_json" | grep '"recovery_rate_percent":' | awk -F': ' '{print $2}' | tr -d ',')

    # 1. GENERATE TEXT REPORT
    if [[ "$format" == "txt" || "$format" == "all" ]]; then
        cat <<EOF > "$txt_path"
================================================================================
          LOSTLINK CAMPUS LOST AND FOUND SYSTEM - $(echo "$report_type" | tr '[:lower:]' '[:upper:]') REPORT
================================================================================
Generated on   : $timestamp_readable
Generated by   : $generated_by
System Engine  : GNU Bash & POSIX Unix Utilities
Data Storage   : Flat Delimited CSV Files
================================================================================

1. EXECUTIVE SUMMARY & KEY PERFORMANCE METRICS
--------------------------------------------------------------------------------
* Total Lost Items Reported     : $t_lost
* Total Found Items Logged      : $t_found
* Pending Claims Under Review   : $p_claims
* Successfully Returned Items   : $t_returned
* Overall Campus Recovery Rate  : $rec_rate%

2. RECENT LOST ITEM REPORTS
--------------------------------------------------------------------------------
$(awk -F',' '
BEGIN { printf "%-8s | %-24s | %-12s | %-20s | %-10s\n", "ID", "TITLE", "CATEGORY", "LOCATION", "STATUS"; print "--------------------------------------------------------------------------------" }
NR > 1 { printf "%-8s | %-24.24s | %-12.12s | %-20.20s | %-10s\n", $1, $2, $3, $5, $9 }
' "$LOST_CSV")

3. RECENT FOUND ITEMS LOGGED
--------------------------------------------------------------------------------
$(awk -F',' '
BEGIN { printf "%-8s | %-24s | %-12s | %-20s | %-10s\n", "ID", "TITLE", "CATEGORY", "LOCATION", "STATUS"; print "--------------------------------------------------------------------------------" }
NR > 1 { printf "%-8s | %-24.24s | %-12.12s | %-20.20s | %-10s\n", $1, $2, $3, $5, $9 }
' "$FOUND_CSV")

4. PENDING CLAIMS AWAITING VERIFICATION
--------------------------------------------------------------------------------
$(awk -F',' '
BEGIN { printf "%-8s | %-8s | %-12s | %-12s | %-24s\n", "CLAIM ID", "ITEM ID", "CLAIMED BY", "STATUS", "PROOF DETAILS"; print "--------------------------------------------------------------------------------" }
NR > 1 && $6 == "pending" { printf "%-8s | %-8s | %-12s | %-12s | %-24.24s\n", $1, $2, $3, $6, $4 }
' "$CLAIMS_CSV")

5. SYSTEM AUDIT HIGHLIGHTS (RECENT 5 ACTIVITIES)
--------------------------------------------------------------------------------
$(tail -n 5 "$AUDIT_LOG")

================================================================================
[End of Report - Generated by LostLink Automated Report Engine]
================================================================================
EOF
    fi

    # 2. GENERATE STANDALONE HTML REPORT
    if [[ "$format" == "html" || "$format" == "all" ]]; then
        cat <<EOF > "$html_path"
<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <title>LostLink $(echo "$report_type" | awk '{print toupper(substr($0,1,1)) substr($0,2)}') Report</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, Helvetica, Arial, sans-serif; background-color: #f8fafc; color: #1e293b; margin: 0; padding: 30px; }
    .container { max-width: 900px; margin: 0 auto; background: #ffffff; padding: 40px; border-radius: 12px; box-shadow: 0 4px 6px -1px rgba(0,0,0,0.1); border: 1px solid #e2e8f0; }
    .header { border-bottom: 2px solid #0284c7; padding-bottom: 20px; margin-bottom: 30px; display: flex; justify-content: space-between; align-items: center; }
    .title { margin: 0; font-size: 26px; color: #0f172a; font-weight: 800; }
    .meta { color: #64748b; font-size: 14px; margin-top: 6px; }
    .badge { display: inline-block; padding: 4px 12px; background: #0284c7; color: white; border-radius: 9999px; font-weight: 600; font-size: 12px; text-transform: uppercase; }
    .grid { display: grid; grid-template-columns: repeat(4, 1fr); gap: 16px; margin-bottom: 30px; }
    .card { background: #f1f5f9; padding: 18px; border-radius: 8px; border-left: 4px solid #0284c7; }
    .card-val { font-size: 28px; font-weight: bold; color: #0f172a; margin-top: 4px; }
    .card-lbl { font-size: 13px; color: #64748b; font-weight: 500; }
    h2 { font-size: 18px; color: #0f172a; margin-top: 30px; margin-bottom: 12px; border-left: 3px solid #0284c7; padding-left: 8px; }
    table { width: 100%; border-collapse: collapse; margin-top: 10px; font-size: 14px; }
    th { background: #f8fafc; text-align: left; padding: 10px; border-bottom: 2px solid #cbd5e1; color: #475569; }
    td { padding: 10px; border-bottom: 1px solid #e2e8f0; }
    .status { padding: 2px 8px; border-radius: 4px; font-size: 12px; font-weight: 600; }
    .status-lost { background: #fee2e2; color: #991b1b; }
    .status-found { background: #e0f2fe; color: #0369a1; }
    .status-recovered { background: #dcfce7; color: #15803d; }
    .status-pending { background: #fef3c7; color: #b45309; }
    .footer { margin-top: 40px; padding-top: 20px; border-top: 1px solid #e2e8f0; font-size: 12px; color: #94a3b8; text-align: center; }
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <div>
        <h1 class="title">LostLink Campus Report</h1>
        <div class="meta">Automated Periodic Summary &bull; <strong>$timestamp_readable</strong></div>
      </div>
      <div>
        <span class="badge">$report_type</span>
      </div>
    </div>

    <div class="grid">
      <div class="card">
        <div class="card-lbl">Total Lost Items</div>
        <div class="card-val">$t_lost</div>
      </div>
      <div class="card">
        <div class="card-lbl">Total Found Items</div>
        <div class="card-val">$t_found</div>
      </div>
      <div class="card">
        <div class="card-lbl">Pending Claims</div>
        <div class="card-val">$p_claims</div>
      </div>
      <div class="card" style="border-left-color: #10b981;">
        <div class="card-lbl">Recovery Rate</div>
        <div class="card-val" style="color: #10b981;">$rec_rate%</div>
      </div>
    </div>

    <h2>Recent Lost Items</h2>
    <table>
      <thead>
        <tr><th>ID</th><th>Title</th><th>Category</th><th>Location</th><th>Status</th></tr>
      </thead>
      <tbody>
        $(awk -F',' 'NR > 1 { printf "<tr><td><b>%s</b></td><td>%s</td><td>%s</td><td>%s</td><td><span class=\"status status-lost\">%s</span></td></tr>\n", $1, $2, $3, $5, $9 }' "$LOST_CSV")
      </tbody>
    </table>

    <h2>Recent Found Items</h2>
    <table>
      <thead>
        <tr><th>ID</th><th>Title</th><th>Category</th><th>Location</th><th>Status</th></tr>
      </thead>
      <tbody>
        $(awk -F',' 'NR > 1 { printf "<tr><td><b>%s</b></td><td>%s</td><td>%s</td><td>%s</td><td><span class=\"status status-found\">%s</span></td></tr>\n", $1, $2, $3, $5, $9 }' "$FOUND_CSV")
      </tbody>
    </table>

    <div class="footer">
      Generated automatically by LostLink Unix Shell Core Engine &bull; University Campus Lost & Found System
    </div>
  </div>
</body>
</html>
EOF
    fi

    log_audit "REPORT" "$generated_by" "Generated $report_type report ($format)"

    print_success "Report generated successfully!"
    [[ -f "$txt_path" ]] && echo -e "  • Text Report: ${COLOR_CYAN}$txt_path${COLOR_RESET}"
    [[ -f "$html_path" ]] && echo -e "  • HTML Report: ${COLOR_CYAN}$html_path${COLOR_RESET}"
}

case "${1:-}" in
    generate)
        generate_report "${2:-daily}" "${3:-all}" "${4:-admin}"
        ;;
    list)
        print_header "AVAILABLE GENERATED REPORTS"
        ls -lh "$REPORTS_DIR"
        ;;
    *)
        echo "Usage: $0 generate [daily|weekly|monthly] [all|txt|html] [user]"
        echo "       $0 list"
        ;;
esac
